<h3 class="mt-4">Day 1 — Arrival in Tbilisi</h3>
<p><strong>03:00 AM</strong> — Land at Tbilisi International (TBS). Most flights from Dubai land at this hour. Private transfer to your hotel.<br>
<strong>09:00</strong> — Vegetarian breakfast at the hotel. <em>Most Tbilisi hotels offer khachapuri (cheese bread) and eggs — pre-order a no-egg / pure-veg plate.</em><br>
<strong>11:00</strong> — Old Tbilisi walking tour: Narikala Fortress (cable car up), Mother of Georgia statue, sulphur baths district (exterior).<br>
<strong>14:00</strong> — Lunch at <strong>Mama Terra</strong> (Old Town) — pure veg, Georgian salads, mushroom-cheese ravioli, badrijani (eggplant rolls). About GEL 35 per person ≈ AED 50.<br>
<strong>16:00</strong> — Sameba (Holy Trinity) Cathedral — Georgia's largest cathedral.<br>
<strong>19:00</strong> — Dinner at <strong>Café Linville</strong> — extensive veg section, good for groups.</p>

<h3 class="mt-4">Day 2 — Mtskheta Day Trip + Wine Region (Veg-Only Stops)</h3>
<p><strong>09:00</strong> — Drive to Mtskheta (UNESCO World Heritage town), 30 minutes from Tbilisi.<br>
<strong>10:00</strong> — Jvari Monastery (6th-century, mountain-top views).<br>
<strong>11:30</strong> — Svetitskhoveli Cathedral.<br>
<strong>13:00</strong> — Lunch at <strong>Salobie</strong>, Mtskheta — famous for lobio (Georgian bean stew), pkhali (vegetable pâtés), mchadi (cornbread). All veg friendly.<br>
<strong>15:00</strong> — Drive to Kakheti wine region OR return to Tbilisi.<br>
<strong>19:30</strong> — Dinner at <strong>Black Lion</strong> in Tbilisi — Georgian-Mediterranean fusion with strong veg menu.</p>

<h3 class="mt-4">Day 3 — Kazbegi Mountain Day Trip</h3>
<p><strong>07:30</strong> — Early breakfast and packed lunch from hotel (we arrange the pure-veg/Jain packing).<br>
<strong>08:00</strong> — Depart for Kazbegi via Military Highway. Stops: Ananuri Fortress, Gudauri ski resort viewpoint, Russia–Georgia Friendship Monument.<br>
<strong>12:30</strong> — Arrive Stepantsminda (Kazbegi village).<br>
<strong>13:00</strong> — 4x4 jeep up to Gergeti Trinity Church (one of the most photographed sites in Georgia).<br>
<strong>15:00</strong> — Lunch at <strong>Café 5047m</strong>, Kazbegi — vegetable khinkali (dumplings), lobio.<br>
<strong>19:00</strong> — Return to Tbilisi. Dinner at hotel.</p>

<h3 class="mt-4">Day 4 — Tbilisi at Leisure + Vegetarian Cooking Class (Optional)</h3>
<p><strong>10:00</strong> — Late breakfast. Free morning for shopping at <strong>Dezerter Bazaar</strong> (best fresh produce, spices, dried fruits) and Rustaveli Avenue (souvenirs, jewellery).<br>
<strong>13:00</strong> — Lunch at <strong>Vong</strong>, Tbilisi — strong Asian-influenced veg menu with Indian options.<br>
<strong>15:00</strong> — <em>Optional:</em> 3-hour Georgian vegetarian cooking class with a local family (khachapuri-making, badrijani, pkhali) — AED 280 per person.<br>
<strong>20:00</strong> — Farewell dinner at <strong>Funicular Restaurant</strong> on Mtatsminda — best panoramic view of the city.</p>

<h3 class="mt-4">Day 5 — Sighnaghi (Wine Country, Veg-Friendly)</h3>
<p><strong>09:00</strong> — Drive to Sighnaghi ("City of Love"), 1.5 hours from Tbilisi.<br>
<strong>11:00</strong> — Walk the medieval city walls. Visit Bodbe Monastery.<br>
<strong>13:00</strong> — Lunch at <strong>Pheasant's Tears</strong> — natural wine restaurant with extensive vegetarian Georgian menu.<br>
<strong>15:00</strong> — Wine tasting (optional — Georgia is the birthplace of wine; grape juice and tea served to those who don't drink).<br>
<strong>19:00</strong> — Return to Tbilisi. Light dinner at hotel.</p>

<h3 class="mt-4">Day 6 — Departure</h3>
<p><strong>06:00</strong> — Hotel breakfast.<br>
<strong>08:00</strong> — Hotel check-out.<br>
<strong>09:00</strong> — Private transfer to Tbilisi airport for departure to Dubai.</p>
